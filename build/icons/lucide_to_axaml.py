#!/usr/bin/env python3
"""Convert Lucide SVG icons (24x24, stroke-based) into an Avalonia ResourceDictionary.

Usage: python3 -I lucide_to_axaml.py <svg-dir> <output.axaml>

Each icon becomes <StreamGeometry x:Key="Icon.<PascalName>"> in a 24x24 coordinate space,
rendered by DevToolBox.App.Shared.Controls.LucideIcon with a round 2px stroke.
Lucide is ISC-licensed; see THIRD_PARTY_NOTICES.md.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG_NS = "{http://www.w3.org/2000/svg}"


def num(value: str | None) -> float:
    return float(value) if value else 0.0


def fmt(value: float) -> str:
    return f"{value:g}"


def circle(cx: float, cy: float, rx: float, ry: float) -> str:
    # Two half-arcs: a single 360° arc is not representable in path data.
    return (f"M{fmt(cx - rx)} {fmt(cy)}"
            f"A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx + rx)} {fmt(cy)}"
            f"A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx - rx)} {fmt(cy)}Z")


def rect(x: float, y: float, w: float, h: float, rx: float, ry: float) -> str:
    if rx == 0 and ry == 0:
        return f"M{fmt(x)} {fmt(y)}H{fmt(x + w)}V{fmt(y + h)}H{fmt(x)}Z"
    rx = rx or ry
    ry = ry or rx
    arc = f"A{fmt(rx)} {fmt(ry)} 0 0 1"
    return (f"M{fmt(x + rx)} {fmt(y)}H{fmt(x + w - rx)}{arc} {fmt(x + w)} {fmt(y + ry)}"
            f"V{fmt(y + h - ry)}{arc} {fmt(x + w - rx)} {fmt(y + h)}"
            f"H{fmt(x + rx)}{arc} {fmt(x)} {fmt(y + h - ry)}"
            f"V{fmt(y + ry)}{arc} {fmt(x + rx)} {fmt(y)}Z")


def points(raw: str, close: bool) -> str:
    coords = raw.replace(",", " ").split()
    pairs = [f"{coords[i]} {coords[i + 1]}" for i in range(0, len(coords), 2)]
    return "M" + "L".join(pairs) + ("Z" if close else "")


NUMBER = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?"
LEADING_RELATIVE_MOVE = re.compile(rf"^\s*m\s*({NUMBER})[\s,]*({NUMBER})(.*)$", re.S)


def absolute_start(d: str) -> str:
    """A leading 'm' is absolute in its own <path>, but not once paths are concatenated."""
    match = LEADING_RELATIVE_MOVE.match(d)
    if not match:
        return d
    x, y, rest = match.groups()
    rest = rest.lstrip(" ,")
    # Extra coordinate pairs after a relative moveto are implicit relative linetos.
    if rest and not rest[0].isalpha():
        rest = "l" + rest
    return f"M{x} {y}{rest}"


def element_to_path(el: ET.Element) -> str:
    tag = el.tag.replace(SVG_NS, "")
    a = el.attrib
    if tag == "path":
        return absolute_start(a["d"])
    if tag == "circle":
        r = num(a.get("r"))
        return circle(num(a.get("cx")), num(a.get("cy")), r, r)
    if tag == "ellipse":
        return circle(num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry")))
    if tag == "rect":
        return rect(num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height")),
                    num(a.get("rx")), num(a.get("ry")))
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        return points(a["points"], close=(tag == "polygon"))
    raise ValueError(f"Unsupported SVG element: {tag}")


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def main() -> None:
    svg_dir, output = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        "  <!-- Generated by build/icons/lucide_to_axaml.py from Lucide (ISC). Do not edit by hand. -->",
    ]
    for svg in sorted(svg_dir.glob("*.svg")):
        root = ET.parse(svg).getroot()
        data = " ".join(element_to_path(child) for child in root if isinstance(child.tag, str))
        lines.append(f'  <StreamGeometry x:Key="Icon.{pascal(svg.stem)}">{data}</StreamGeometry>')
    lines.append("</ResourceDictionary>")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines) - 4} icons to {output}")


if __name__ == "__main__":
    main()
